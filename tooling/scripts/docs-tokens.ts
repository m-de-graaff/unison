// Generates docs/tokens.md from the default theme in packages/tokens/dist/tokens.json.
// CI fails when the committed file is out of date: run `pnpm docs:tokens` after changing tokens.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

interface Entry {
  type: string;
  value: unknown;
  aliasOf?: string;
  tier: "primitive" | "semantic";
  description?: string;
}
interface TokensJson {
  defaultTheme: string;
  themes: Record<string, Record<"light" | "dark", Record<string, Entry>>>;
}

const root = join(import.meta.dirname, "../..");
const json = JSON.parse(
  readFileSync(join(root, "packages/tokens/dist/tokens.json"), "utf8"),
) as TokensJson;
const theme = json.themes[json.defaultTheme];
if (!theme) throw new Error(`tokens.json has no theme ${json.defaultTheme}`);

type Dim = { value: number; unit: string };
const len = (d: Dim) => (d.value === 0 ? "0" : `${d.value}${d.unit}`);

/** A compact, readable value for a table cell. */
function show(e: Entry): string {
  const v = e.value as Record<string, unknown>;
  switch (e.type) {
    case "typography": {
      const t = v as {
        fontSize: Dim;
        lineHeight: Dim;
        fontWeight: number;
        letterSpacing: Dim;
        fontFamily: string[];
      };
      return `${len(t.fontSize)}/${len(t.lineHeight)} ${t.fontWeight} ${len(t.letterSpacing)} ${t.fontFamily[0]}`;
    }
    case "shadow":
      return (e.value as { x: Dim; y: Dim; blur: Dim; spread: Dim; color: { hex: string } }[])
        .map((l) => `${len(l.x)} ${len(l.y)} ${len(l.blur)} ${len(l.spread)} ${l.color.hex}`)
        .join(", ");
    case "transition":
      return "spring" in v
        ? `spring ${JSON.stringify(v.spring)}`
        : `${len(v.duration as Dim)} cubic-bezier(${(v.easing as number[]).join(", ")})`;
    case "motionPreset":
      return "see docs/motion.md";
    default:
      return typeof e.value === "string" || typeof e.value === "number"
        ? String(e.value)
        : JSON.stringify(e.value);
  }
}

const cell = (s: string) => s.replaceAll("|", "\\|");
const semantic = (scheme: "light" | "dark") =>
  Object.entries(theme[scheme])
    .filter(([, e]) => e.tier === "semantic")
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));

const lines = [
  "<!-- Generated by tooling/scripts/docs-tokens.ts from packages/tokens/dist/tokens.json. Don't edit: run `pnpm docs:tokens`. -->",
  "",
  "# Tokens",
  "",
  `Every semantic token of the \`${json.defaultTheme}\` theme. Components and apps use these; primitives (\`color.gray.500\`, \`space.4\`, …) only feed them. Values come from the default \`defineTheme()\` options (accent \`indigo\`, neutral \`gray\`, radius \`md\`, density \`default\`).`,
  "",
];
for (const scheme of ["light", "dark"] as const) {
  lines.push(
    `## ${scheme === "light" ? "Light" : "Dark"}`,
    "",
    "| Token | Value | Alias | Use |",
    "| --- | --- | --- | --- |",
  );
  for (const [path, e] of semantic(scheme)) {
    lines.push(
      `| \`${path}\` | ${cell(show(e))} | ${e.aliasOf ? `\`${e.aliasOf}\`` : "raw"} | ${cell(e.description ?? "")} |`,
    );
  }
  lines.push("");
}
writeFileSync(join(root, "docs/tokens.md"), lines.join("\n"));
console.log(`wrote docs/tokens.md (${semantic("light").length} semantic tokens)`);
