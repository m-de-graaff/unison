// `pnpm new:component <kebab-name>`: scaffolds every file in docs/component-checklist.md with a
// working stub (a placeholder box), wires up the exports and a parity fixture, and prints the
// remaining TODOs.
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";

const root = resolve(import.meta.dirname, "../..");
const name = process.argv[2] ?? "";

if (!/^[a-z][a-z0-9-]*$/.test(name)) {
  console.error("Usage: pnpm new:component <kebab-name>");
  process.exit(1);
}

const pascal = name.replace(/(^|-)([a-z0-9])/g, (_, __, c: string) => c.toUpperCase());
const camel = pascal.charAt(0).toLowerCase() + pascal.slice(1);

const p = (...parts: string[]) => join(root, ...parts);

const files: Record<string, string> = {
  [p("packages/core/src/components", name, `${name}.types.ts`)]:
    `import type { ReactNode } from "react";

export interface ${pascal}Props {
  testID?: string; // web renders it as data-testid
  children?: ReactNode;
}
`,
  [p("packages/core/src/components", name, `${name}.styles.ts`)]:
    `// Token paths only, never raw values.
export const ${camel}Styles = {
  size: "size.demo-box",
  radius: "radius.card",
  border: "color.border",
  background: "color.surface",
} as const;
`,
  [p("packages/react/src", `${name}.tsx`)]:
    `import { type ${pascal}Props, ${camel}Styles } from "@unison-ui/core";
import { cssVar } from "./css-var";

// TODO: placeholder renderer generated by \`pnpm new:component\`.
export function ${pascal}({ testID, children }: ${pascal}Props) {
  return (
    <div
      data-testid={testID}
      style={{
        boxSizing: "border-box",
        width: cssVar(${camel}Styles.size),
        height: cssVar(${camel}Styles.size),
        borderRadius: cssVar(${camel}Styles.radius),
        border: \`1px solid \${cssVar(${camel}Styles.border)}\`,
        background: cssVar(${camel}Styles.background),
      }}
    >
      {children}
    </div>
  );
}
`,
  [p("packages/native/src", `${name}.tsx`)]:
    `import { type ${pascal}Props, ${camel}Styles } from "@unison-ui/core";
import { View } from "react-native";
import { token, useUnisonTheme } from "./theme";

// TODO: placeholder renderer generated by \`pnpm new:component\`.
export function ${pascal}({ testID, children }: ${pascal}Props) {
  const theme = useUnisonTheme();
  const size = token(theme, ${camel}Styles.size);
  return (
    <View
      testID={testID}
      style={{
        width: size,
        height: size,
        borderRadius: token(theme, ${camel}Styles.radius),
        borderWidth: 1,
        borderColor: token(theme, ${camel}Styles.border),
        backgroundColor: token(theme, ${camel}Styles.background),
      }}
    >
      {children}
    </View>
  );
}
`,
  [p("packages/parity/src/fixtures", `${name}.ts`)]: `export const ${camel}Fixture = {
  component: "${name}",
  cases: {
    default: {},
  },
} as const;
`,
};

const existing = Object.keys(files).filter((f) => existsSync(f));
if (existing.length > 0) {
  console.error(
    `Refusing to overwrite:\n${existing.map((f) => `  ${relative(root, f)}`).join("\n")}`,
  );
  process.exit(1);
}

function edit(file: string, change: (text: string) => string): string {
  const before = readFileSync(file, "utf8");
  const after = change(before);
  if (after === before) throw new Error(`could not update ${relative(root, file)}`);
  writeFileSync(file, after);
  return file;
}

const append = (line: string) => (text: string) => `${text.trimEnd()}\n${line}\n`;

const touched: string[] = [];
for (const [file, content] of Object.entries(files)) {
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, content);
  touched.push(file);
}

touched.push(
  edit(
    p("packages/core/src/index.ts"),
    append(
      `export { ${camel}Styles } from "./components/${name}/${name}.styles";\n` +
        `export type { ${pascal}Props } from "./components/${name}/${name}.types";`,
    ),
  ),
  edit(
    p("packages/react/src/index.ts"),
    append(
      `export type { ${pascal}Props } from "@unison-ui/core";\nexport { ${pascal} } from "./${name}";`,
    ),
  ),
  edit(
    p("packages/native/src/index.ts"),
    append(
      `export type { ${pascal}Props } from "@unison-ui/core";\nexport { ${pascal} } from "./${name}";`,
    ),
  ),
  edit(p("packages/parity/src/fixtures/index.ts"), (text) =>
    text
      .replace(/^(import .*\n)(?!import)/m, `$1import { ${camel}Fixture } from "./${name}";\n`)
      .replace(/export const fixtures = \[([^\]]*)\] as const;/, (_, list: string) => {
        return `export const fixtures = [${list.trim()}, ${camel}Fixture] as const;`;
      }),
  ),
  edit(p("packages/parity/src/registry.tsx"), (text) =>
    text
      .replace(/import \{ ([^}]*) \} from "@unison-ui\/ui";/, (_, list: string) => {
        return `import { ${list.trim()}, ${pascal} } from "@unison-ui/ui";`;
      })
      .replace(/export const registry = \{([^}]*)\} as const;/, (_, body: string) => {
        return `export const registry = { ${body.trim()}, "${name}": ${pascal} } as const;`;
      }),
  ),
);

// Keep the generated code in the repo's style.
execFileSync("pnpm", ["exec", "biome", "check", "--write", ...touched], {
  cwd: root,
  stdio: "ignore",
});

console.log(`Created ${pascal}:`);
for (const file of touched) console.log(`  ${relative(root, file)}`);
console.log(`
Remaining TODOs (docs/component-checklist.md):
  - Real styles and variants in ${name}.styles.ts (token paths only)
  - A motion spec (${name}.motion.ts) if it animates
  - A headless hook in packages/core if it has state
  - Parity cases for every variant in packages/parity/src/fixtures/${name}.ts
  - Unit tests: packages/react/test and packages/native/test
  - A changeset: pnpm changeset`);
