import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import type { ThemeBuild } from "./build";
import { NATIVE_TYPES, type NativeEntry, nativeEntries, themeType } from "./emit-native";

const union = (names: string[]) =>
  names.length === 0 ? "never" : names.map((n) => JSON.stringify(n)).join(" | ");

/** Names under a path prefix, e.g. `color.` → `fg`, `fg-muted`, … */
const under = (entries: NativeEntry[], prefix: string) =>
  entries.filter((e) => e.path.startsWith(prefix)).map((e) => e.path.slice(prefix.length));

/**
 * The generated declarations: `UnisonTheme`, the name unions and `SemanticTokenValues`, whose keys
 * are the semantic paths components may use. Same shape for every theme, so the first one is used.
 */
export function typesSource(themes: ThemeBuild[]): string {
  const first = themes[0];
  if (!first) throw new Error("emitTypes needs at least one theme");
  const all = nativeEntries(first, first.light);
  const semantic = all.filter((e) => e.tier === "semantic");
  return [
    "// Generated by @unison-ui/tokens. Do not edit.",
    'import type { MotionPresetValue, ResolvedTransition } from "@unison-ui/tokens/motion";',
    "",
    "/** A text style as React Native takes it; no `fontWeight`, the face carries the weight. */",
    "export interface NativeTextStyle {",
    "  readonly fontFamily: string;",
    "  readonly fontSize: number;",
    "  readonly lineHeight: number;",
    "  readonly letterSpacing: number;",
    "}",
    "",
    `export interface UnisonTheme ${themeType(all)}`,
    "",
    `export type SemanticColor = ${union(under(semantic, "color."))};`,
    `export type TextStyle = ${union(semantic.filter((e) => e.ts === NATIVE_TYPES.text).map((e) => e.path.slice("text.".length)))};`,
    `export type RadiusToken = ${union(under(semantic, "radius."))};`,
    `export type ShadowToken = ${union(under(all, "shadow."))};`,
    `export type ElevationToken = ${union(under(all, "elevation."))};`,
    `export type MotionPreset = ${union(under(all, "motion.preset."))};`,
    `export type ThemeName = ${union(themes.map((t) => t.name))};`,
    "",
    "/** Semantic token paths and the value each has in a `UnisonTheme`. */",
    "export interface SemanticTokenValues {",
    ...semantic.map((e) => `  ${JSON.stringify(e.path)}: ${e.ts};`),
    "}",
    "export type SemanticTokenPath = keyof SemanticTokenValues;",
    "",
  ].join("\n");
}

/** Writes dist/types.d.ts (plus an empty types.js, so the "./types" export has a runtime file). */
export function emitTypes(outDir: string, themes: ThemeBuild[]): string[] {
  mkdirSync(outDir, { recursive: true });
  const dts = join(outDir, "types.d.ts");
  const js = join(outDir, "types.js");
  writeFileSync(dts, typesSource(themes));
  writeFileSync(js, "export {};\n");
  return [dts, js];
}
